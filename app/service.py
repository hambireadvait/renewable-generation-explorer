DEMO_WARNING = ("DEMO MODE: results use SYNTHETIC weather generated by this app, not real data. "
                "Do not use them for any decision.")


@dataclass
class Computed:
    payload: dict[str, Any]
    hourly: pd.DataFrame  # UTC index; columns per technology (kW == kWh per hour)


def _solar_cfg(s: SolarInput) -> SolarConfig:
    return SolarConfig(
        capacity_kwp=s.capacity_kwp, tilt_deg=s.tilt_deg, azimuth_deg=s.azimuth_deg, mounting=s.mounting,
        dc_ac_ratio=s.dc_ac_ratio, inverter_efficiency_pct=s.inverter_efficiency_pct,
        temp_coeff_pct_per_c=s.temp_coeff_pct_per_c, albedo=s.albedo, losses_pct=dict(s.losses_pct),
    )


def _wind_cfg(w: WindInput) -> WindConfig:
    return WindConfig(
        turbine_rated_kw=w.turbine_rated_kw, n_turbines=w.n_turbines, hub_height_m=w.hub_height_m,
        rotor_diameter_m=w.rotor_diameter_m, power_curve=[tuple(p) for p in w.power_curve] if w.power_curve else None,
        cut_in_ms=w.cut_in_ms, rated_speed_ms=w.rated_speed_ms, cut_out_ms=w.cut_out_ms,
        air_density_correction=w.air_density_correction, losses_pct=dict(w.losses_pct),
    )


def _area_info(req_loc, weather: WeatherSeries, resolution_deg: float | None) -> tuple[dict[str, Any] | None, list[str]]:
    warnings: list[str] = []
    if req_loc.area is None:
        return None, warnings
    a = req_loc.area
    lat_mid = math.radians((a.north + a.south) / 2)
    km_ns = (a.north - a.south) * 111.32
    km_ew = (a.east - a.west) * 111.32 * math.cos(lat_mid)
    span = max(a.north - a.south, a.east - a.west)
    info = {"bbox": a.model_dump(), "approx_area_km2": round(km_ns * km_ew, 2),
            "evaluated_at": "centroid", "centroid": [req_loc.latitude, req_loc.longitude]}
    warnings.append(
        f"Area selected (~{info['approx_area_km2']:,} km²): the resource was evaluated at its centroid only. "
        "The app does not check land suitability, terrain, land use, permits or grid access within the area."
    )
    if resolution_deg and span > resolution_deg:
        warnings.append(f"The area spans more than one data grid cell (~{resolution_deg}°); resource may vary "
                        "across it more than a single centroid estimate shows.")
    return info, warnings


_RESOLUTION_DEG = {"nasa_power": 0.5, "open_meteo_era5": 0.25, "demo": None}


def _site(req_loc, weather: WeatherSeries, tz: str) -> dict[str, Any]:
    return {
        "requested": {"latitude": req_loc.latitude, "longitude": req_loc.longitude, "label": req_loc.label},
        "data_grid_point": {"latitude": weather.latitude, "longitude": weather.longitude,
                            "elevation_m": weather.elevation_m},
        "timezone": tz,
    }


def _common_warnings(weather: WeatherSeries, lat: float) -> list[str]:
    w = []
    if weather.source.is_demo:
        w.append(DEMO_WARNING)
    if weather.quality.get("max_missing_pct", 0) > 0:
        w.append(f"Source data had missing hours (worst variable {weather.quality['max_missing_pct']}%); "
                 f"{weather.quality.get('note', '')}")
    if abs(lat) > 60:
        w.append("High-latitude site: snow, low sun angles and data quality are poorly represented by this model.")
    return w


def assess(req: AssessRequest, registry: Registry) -> Computed:
    provider = registry.historical[req.provider]
    loc = req.location
    weather = provider.fetch_years(loc.latitude, loc.longitude, req.start_year, req.end_year)
    tz = local_timezone(loc.latitude, loc.longitude)
    n_years = req.end_year - req.start_year + 1
    warnings = _common_warnings(weather, loc.latitude)
    area, area_warn = _area_info(loc, weather, _RESOLUTION_DEG.get(req.provider))
    warnings += area_warn
    if not weather.source.is_demo:
        warnings.append("Different resource datasets disagree: in a check at Jaisalmer (2021–2025) NASA POWER and ERA5 "
                        "differed by ~10% in solar yield and ~10% in mean hub-height wind speed (≈40% in wind energy). "
                        "Re-run with the other historical source to see the spread for your site.")
    if n_years < 3:
        warnings.append(f"Only {n_years} year(s) of history used; long-term averages and year-to-year spread are "
                        "uncertain. 10+ years gives a more reliable long-term average.")
    hourly = pd.DataFrame(index=weather.data.index)
    results: dict[str, Any] = {}

    solar_cfg = wind_cfg = None
    if req.solar:
        solar_cfg = _solar_cfg(req.solar)
        s_hourly, s_meta = simulate_solar(weather, solar_cfg)
        hourly["solar_kw"] = s_hourly["ac_kw"]
        hourly["poa_wm2"] = s_hourly["poa_wm2"]
        results["solar"] = {
            "capacity_kw": solar_cfg.capacity_kwp,
            "capacity_basis": "kWp DC",
            "summary": summarize(s_hourly["ac_kw"], tz, solar_cfg.capacity_kwp, include_daily=req.include_daily),
            "metrics": {**solar_metrics(s_hourly, solar_cfg, n_years),
                        "approx_inverter_clipping_kwh_per_year": round(s_meta["approx_inverter_clipping_kwh"] / n_years, 1)},
            "assumptions": s_meta["assumptions"],
            "notes": s_meta["notes"],
        }
        warnings += s_meta["notes"]
    if req.wind:
        wind_cfg = _wind_cfg(req.wind)
        w_hourly, w_meta = simulate_wind(weather, wind_cfg)
        hourly["wind_kw"] = w_hourly["ac_kw"]
        hourly["wind_hub_ms"] = w_hourly["wind_hub_ms"]
        cap = wind_cfg.turbine_rated_kw * wind_cfg.n_turbines
        results["wind"] = {
            "capacity_kw": cap,
            "capacity_basis": "kW rated",
            "summary": summarize(w_hourly["ac_kw"], tz, cap, include_daily=req.include_daily),
            "metrics": wind_metrics(w_hourly, wind_cfg, n_years),
            "assumptions": w_meta["assumptions"],
            "notes": w_meta["notes"],
        }
        warnings += w_meta["notes"]
        warnings.append("Reanalysis/satellite wind data is smoothed over tens of km and does not capture local "
                        "terrain, roughness or obstacles. A bankable wind assessment needs on-site measurement "
                        "(≥12 months met mast/LiDAR) correlated to long-term data.")

    if req.solar and req.wind and (req.hybrid is None or req.hybrid.enabled):
        limit = req.hybrid.export_limit_kw if req.hybrid else None
        frame, h_meta = hybrid_model.combine(hourly["solar_kw"], hourly["wind_kw"], limit)
        hourly["hybrid_export_kw"] = frame["export_kw"]
        hourly["hybrid_curtailed_kw"] = frame["curtailed_kw"]
        cap = limit or (solar_cfg.capacity_kwp / solar_cfg.dc_ac_ratio + results["wind"]["capacity_kw"])
        results["hybrid"] = {
            "capacity_kw": cap,
            "capacity_basis": "grid export limit" if limit else "solar AC + wind rated (no export limit)",
            "summary": summarize(frame["export_kw"], tz, cap, include_daily=req.include_daily),
            "curtailed_kwh_per_year": round(float(frame["curtailed_kw"].sum()) / n_years, 1),
            **h_meta,
        }

    payload = {
        "use_case": "long_term_average",
        "label": "Long-term average generation from historical weather — not a forecast",
        "is_demo": weather.source.is_demo,
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "app_version": __version__,
        "model_versions": {"pvlib": pvlib.__version__},
        "period": {"start_year": req.start_year, "end_year": req.end_year, "n_years": n_years,
                   "aggregation": "Per-year totals on UTC calendar years; daily/monthly/diurnal in local time"},
        "site": _site(loc, weather, tz),
        "area": area,
        "source": weather.source.as_dict(),
        "data_quality": weather.quality,
        "results": results,
        "warnings": list(dict.fromkeys(warnings)),
        "not_assessed": ["land suitability or availability", "permits and regulation", "grid connection capacity or cost",
                         "grid curtailment", "site-specific shading or terrain effects",
                         "costs, revenue or financial viability"],
        "request": req.model_dump(mode="json"),
    }
    return Computed(payload=payload, hourly=hourly)


def forecast(req: ForecastRequest, registry: Registry, weather: WeatherSeries | None = None) -> Computed:
    """Near-term generation for the forecast window (default: the next 7 days).

    `weather` may be supplied already parsed (forecast fetched by the visitor's browser when the
    server's Open-Meteo quota is exhausted); otherwise the server fetches it.
    """
    loc = req.location
    if weather is None:
        weather = registry.forecast[req.provider].fetch_forecast(loc.latitude, loc.longitude, req.days)
    tz = local_timezone(loc.latitude, loc.longitude)
    zone = ZoneInfo(tz)
    warnings = _common_warnings(weather, loc.latitude)
    area, area_warn = _area_info(loc, weather, None)
    warnings += area_warn
    warnings.append("Forecast skill drops with lead time: the first 2–3 days are far more reliable than days 5–16. "
                    "Cloud timing and wind speed errors of ±20–50% on a given day are normal.")
    warnings.append("This reflects the forecast weather for these specific days, not a typical week. Use the "
                    "long-term average tab for typical monthly/annual generation.")
    hours = len(weather.data)
    if hours < req.days * 24:
        warnings.append(f"The provider supplied {hours} of the {req.days * 24} requested hours "
                        f"(about {hours / 24:.1f} days); totals cover only that window.")
    hourly = pd.DataFrame(index=weather.data.index)
    results: dict[str, Any] = {}
    solar_cfg = None
    if req.solar:
        solar_cfg = _solar_cfg(req.solar)
        s, meta = simulate_solar(weather, solar_cfg)
        hourly["solar_kw"] = s["ac_kw"]
        results["solar"] = {"capacity_kw": solar_cfg.capacity_kwp, "capacity_basis": "kWp DC",
                            "assumptions": meta["assumptions"]}
        warnings += meta["notes"]
    if req.wind:
        cfg_w = _wind_cfg(req.wind)
        w, meta = simulate_wind(weather, cfg_w)
        hourly["wind_kw"] = w["ac_kw"]
        hourly["wind_hub_ms"] = w["wind_hub_ms"]
        results["wind"] = {"capacity_kw": cfg_w.turbine_rated_kw * cfg_w.n_turbines, "capacity_basis": "kW rated",
                           "assumptions": meta["assumptions"]}
        warnings += meta["notes"]
    if req.solar and req.wind and (req.hybrid is None or req.hybrid.enabled):
        limit = req.hybrid.export_limit_kw if req.hybrid else None
        frame, h_meta = hybrid_model.combine(hourly["solar_kw"], hourly["wind_kw"], limit)
        hourly["hybrid_kw"] = frame["export_kw"]
        hourly["hybrid_curtailed_kw"] = frame["curtailed_kw"]
        cap = limit or (solar_cfg.capacity_kwp / solar_cfg.dc_ac_ratio + results["wind"]["capacity_kw"])
        results["hybrid"] = {"capacity_kw": cap,
                             "capacity_basis": "grid export limit" if limit else "solar AC + wind rated (no export limit)",
                             **h_meta}

    for tech, r in results.items():
        col = hourly[f"{tech}_kw"]
        peak_at = col.idxmax()
        r["totals"] = {
            "energy_kwh": round(float(col.sum()), 2),
            "capacity_factor_pct": round(100 * float(col.sum()) / (r["capacity_kw"] * hours), 2) if hours else None,
            "average_per_day_kwh": round(float(col.sum()) / (hours / 24), 2) if hours else None,
            "peak_kw": round(float(col.max()), 2),
            "peak_time_local": peak_at.tz_convert(zone).isoformat() if col.max() > 0 else None,
        }
        if tech == "hybrid":
            r["totals"]["curtailed_kwh"] = round(float(hourly["hybrid_curtailed_kw"].sum()), 2)

    hourly["ghi_wm2"] = weather.data["ghi"]
    hourly["temp_air_c"] = weather.data["temp_air"]
    hourly["wind_10m_ms"] = weather.data["wind_10m"]
    local = hourly.tz_convert(zone)
    hourly_rows = [{"time_local": ts.isoformat(), **{k: round(float(v), 3) for k, v in row.items()}}
                   for ts, row in local.iterrows()]
    techs = list(results)
    daily = []
    for day, part in local.groupby(local.index.date):
        row: dict[str, Any] = {"date": str(day), "weekday": pd.Timestamp(day).day_name(), "hours": len(part),
                               "partial_day": len(part) < 23}
        for t in techs:
            row[f"{t}_kwh"] = round(float(part[f"{t}_kw"].sum()), 2)
            row[f"{t}_peak_kw"] = round(float(part[f"{t}_kw"].max()), 2)
        row["irradiation_kwh_m2"] = round(float(part["ghi_wm2"].sum()) / 1000, 3)
        if "wind_hub_ms" in part:
            row["mean_hub_wind_ms"] = round(float(part["wind_hub_ms"].mean()), 2)
        row["mean_temp_c"] = round(float(part["temp_air_c"].mean()), 1)
        row["max_temp_c"] = round(float(part["temp_air_c"].max()), 1)
        daily.append(row)
    headline = "hybrid" if "hybrid" in results else techs[0]
    full_days = [d for d in daily if not d["partial_day"]] or daily
    best = max(full_days, key=lambda d: d[f"{headline}_kwh"])
    worst = min(full_days, key=lambda d: d[f"{headline}_kwh"])
    start_local = pd.Timestamp(weather.extra["forecast_start_utc"]).tz_convert(zone)
    end_local = pd.Timestamp(weather.extra["forecast_end_utc"]).tz_convert(zone)
    payload = {
        "use_case": "near_term_forecast",
        "label": f"Generation forecast for the next {req.days} day{'s' if req.days != 1 else ''}",
        "fetched_by": weather.extra.get("fetched_by", "server"),
        "is_demo": weather.source.is_demo,
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "app_version": __version__,
        "model_versions": {"pvlib": pvlib.__version__},
        "forecast_period": {
            "days_requested": req.days,
            "start_utc": weather.extra.get("forecast_start_utc"),
            "end_utc": weather.extra.get("forecast_end_utc"),
            "start_local": start_local.isoformat(),
            "end_local": end_local.isoformat(),
            "hours": hours,
            "model": weather.extra.get("forecast_model"),
        },
        "site": _site(loc, weather, tz),
        "area": area,
        "source": weather.source.as_dict(),
        "results": results,
        "summary": {
            "headline_technology": headline,
            "total_kwh": results[headline]["totals"]["energy_kwh"],
            "best_day": {"date": best["date"], "kwh": best[f"{headline}_kwh"]},
            "lowest_day": {"date": worst["date"], "kwh": worst[f"{headline}_kwh"]},
        },
        "hourly": hourly_rows,
        "daily": daily,
        "totals": {f"{t}_kwh": results[t]["totals"]["energy_kwh"] for t in techs},
        "warnings": list(dict.fromkeys(warnings)),
        "not_assessed": ["grid availability or curtailment by the grid operator", "plant outages beyond the availability loss",
                         "site-specific shading or terrain effects", "costs, revenue or financial viability"],
        "request": req.model_dump(mode="json"),
    }
    return Computed(payload=payload, hourly=hourly)
